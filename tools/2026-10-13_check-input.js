'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const assert = require('assert');
const handlers = {};
const root = {addEventListener:(name,fn)=>(handlers[name] ||= []).push(fn)};
const sandbox = {window:root, navigator:{}, document:{querySelectorAll:()=>[]}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/input.js'),'utf8'),sandbox);
const I=root.CQ.Input;
const dispatch=(type,event={})=>(handlers[type]||[]).forEach(fn=>fn(event));
let confirms=0;
I.on('confirm',()=>confirms++);
function key(code, target={closest:()=>null}) { return {code,target,preventDefault(){},repeat:false}; }
dispatch('keydown',key('Space'));
assert.strictEqual(I.poll().jumpPressed,true);
assert.strictEqual(I.poll().jumpPressed,false,'held jump must not retrigger every poll');
I.reset();
dispatch('keydown',key('Space'));
assert.strictEqual(I.poll().jumpPressed,true,'jump must work after reset');
dispatch('blur');
assert.strictEqual(I.poll().jump,false,'blur must clear held keys');
const before=confirms;
dispatch('keydown',key('Space',{closest:()=>({tagName:'INPUT'})}));
assert.strictEqual(confirms,before,'Space on settings input must not trigger menu confirmation');
assert.strictEqual(I.poll().jump,false,'Space on settings must not queue a jump');
let pauses=0;
I.on('pause',()=>pauses++);
dispatch('keydown',key('Escape',{closest:()=>({tagName:'INPUT'})}));
assert.strictEqual(pauses,1,'Escape still closes a menu while a native setting is focused');
console.log('PASS keyboard reset and native settings keyboard handling');

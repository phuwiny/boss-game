/* Offline asset normalization only. No runtime dependency on sharp. */
const fs=require('node:fs'),path=require('node:path');
let sharp;try{sharp=require('sharp');}catch{sharp=require(path.resolve(path.dirname(process.execPath),'../node_modules/sharp'));}
const poses=['idle','blink','run1','run2','run3','run4','jump','fall','dead'];
const D=2,W=54*D,H=48*D,AX=32*D;
const out={version:'concept-2026-10-17-aclaire-arm-swing',w:54,h:48,ax:32,density:D,palette:[null],frames:{}};
const colors=new Map(),sheets=[];
function bounds(data,w,h){let x0=w,y0=h,x1=-1,y1=-1;for(let y=0;y<h;y++)for(let x=0;x<w;x++)if(data[(y*w+x)*4+3]>=128){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}if(x1<0)throw Error('Empty sprite');return {left:x0,top:y0,width:x1-x0+1,height:y1-y0+1};}
(async()=>{
for(const id of ['bobo','mew','aclaire']){
 const cells=[];
 for(const pose of poses){
  const i=poses.indexOf(pose),cols=3,rows=3;
  const file=`assets/characters/2026-10-15_${id}-source.png`,meta=await sharp(file).metadata();
  const left=Math.round(i%cols*meta.width/cols),top=Math.round(Math.floor(i/cols)*meta.height/rows),width=Math.round((i%cols+1)*meta.width/cols)-left,height=Math.round((Math.floor(i/cols)+1)*meta.height/rows)-top;
  const {data,info}=await sharp(file).extract({left,top,width,height}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const box=bounds(data,info.width,info.height);
  if(box.left===0||box.top===0||box.left+box.width===width||box.top+box.height===height)throw Error(`${id}/${i} touches slot edge`);
  cells.push({data,info,box});
 }
 // One shared scale for all poses; never stretch individual animation frames.
 const scale=Math.min((id==='bobo'?31:43)/Math.max(...cells.map(c=>c.box.height)),48/Math.max(...cells.map(c=>c.box.width)));
 // Keep the shipped nine-pose scale. Only Aclaire's center Run frame comes from the revised sheet.
 if(id==='aclaire'){
  const file='assets/characters/2026-10-17_aclaire-arm-swing-source.png';
  const meta=await sharp(file).metadata(),i=poses.indexOf('run3');
  const left=Math.round(i%3*meta.width/3),top=Math.round(Math.floor(i/3)*meta.height/3);
  const width=Math.round((i%3+1)*meta.width/3)-left,height=Math.round((Math.floor(i/3)+1)*meta.height/3)-top;
  const {data,info}=await sharp(file).extract({left,top,width,height}).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const box=bounds(data,info.width,info.height);
  if(box.left===0||box.top===0||box.left+box.width===width||box.top+box.height===height)throw Error('aclaire/run3 touches slot edge');
  cells[i]={data,info,box};
 }
 out.frames[id]={};
 for(let i=0;i<poses.length;i++){
  // Preserve the original rounded logical bounds exactly; only sample density changes.
  const {data,info,box}=cells[i],logicalW=Math.round(box.width*scale),logicalH=Math.round(box.height*scale),w=logicalW*D,h=logicalH*D;
  const pixels=await sharp(data,{raw:{width:info.width,height:info.height,channels:4}}).extract(box).resize(w,h,{kernel:'lanczos3'}).raw().toBuffer();
  // Faces sit forward of hair/headband tails. Align the core body, not the whole silhouette.
  const center=Math.round(logicalW*(id==='bobo'?0.65:0.59))*D,dx=AX-center,dy=H-D-h;
  if(dx<0||dx+w>W)throw Error(`${id}/${poses[i]} exceeds frame`);
  const frame=Buffer.alloc(W*H*4),codes=new Array(W*H).fill('000'),mask=new Array(W*H).fill('.');
  for(let y=0;y<h;y++)for(let x=0;x<w;x++){
   const p=(y*w+x)*4;if(pixels[p+3]<128)continue;
   const rgb=[0,1,2].map(c=>Math.round(pixels[p+c]/17)*17),[r,g,b]=rgb;
   const color='#'+rgb.map(v=>v.toString(16).padStart(2,'0')).join('');
   if(!colors.has(color)){colors.set(color,out.palette.length);out.palette.push(color);}
   const n=(dy+y)*W+dx+x;codes[n]=colors.get(color).toString(16).padStart(3,'0');
   frame.set([...rgb,255],n*4);
   if(id==='bobo'&&r>130&&g>40&&g<200&&b<110&&r>g*1.25)mask[n]='a';
   // Mew's hair and skirt share orange shadows: recolor the blue blouse only.
   if(id==='mew'&&y>h*.48&&y<h*.82&&b>r*1.25&&b>g*1.1)mask[n]='a';
   if(id==='aclaire'&&y>h*.48){if(r>110&&b>70&&r>g*1.2&&b>g*1.1)mask[n]='a';else if(b>r*1.3&&b>g*1.05)mask[n]='b';}
  }
  out.frames[id][poses[i]]={pixels:codes.join(''),mask:mask.join('')};
  await sharp(frame,{raw:{width:W,height:H,channels:4}}).png().toFile(`assets/characters/2026-10-16_${id}-${poses[i]}-hd.png`);
  sheets.push({input:await sharp(frame,{raw:{width:W,height:H,channels:4}}).resize(W*2,H*2,{kernel:'nearest'}).png().toBuffer(),left:i*W*2,top:['bobo','mew','aclaire'].indexOf(id)*H*2});
 }
 console.log(id,'original logical scale',scale);
}
if(out.palette.length>4096)throw Error('Palette overflow');
fs.writeFileSync('js/2026-10-15_character-art.js','/* Generated by tools/2026-10-15_build-character-art.cjs; source art in assets/characters. */\n(function(root){\n(root.CQ=root.CQ||{}).CharacterArt='+JSON.stringify(out)+';\n})(typeof window!=="undefined"?window:globalThis);\n');
await sharp({create:{width:poses.length*W*2,height:3*H*2,channels:4,background:'#d5e7cf'}}).composite(sheets).png().toFile('assets/characters/2026-10-15_normalized-preview.png');
console.log('27 original poses at 2x density; palette',out.palette.length);
})();

/* Build the Stage 4 motion manifest from the approved 4x4 source and normalized sheets.
 * Normalization was performed during the visual handoff; this step validates it
 * and keeps the browser manifest deterministic without a runtime image library.
 */
const fs = require('node:fs');
const path = require('node:path');
let sharp;
try { sharp = require('sharp'); }
catch { sharp = require(path.resolve(path.dirname(process.execPath), '../node_modules/sharp')); }
const root = path.resolve(__dirname, '..');
const poses = ['run1','run2','run3','run4','run5','run6','run7','run8','jumpUp','jumpApex','jumpFall','land','dead1','dead2','dead3'];
const ids = ['bobo','mew','aclaire'];
const frameW = 108, frameH = 96;

function countOpaque(data, width, left, top, w, h) {
  let count = 0;
  for (let y = top; y < top + h; y++) for (let x = left; x < left + w; x++) {
    if (data[(y * width + x) * 4 + 3] >= 128) count++;
  }
  return count;
}

(async function () {
  const sheets = {};
  for (const id of ids) {
    const src = path.join(root, `assets/characters/2026-11-15_${id}-motion-v2-source.png`);
    const frames = path.join(root, `assets/characters/2026-11-15_${id}-motion-v2-frames.png`);
    const [sm, fm] = await Promise.all([sharp(src).metadata(), sharp(frames).metadata()]);
    if (fm.width !== frameW * 4 || fm.height !== frameH * 4) throw Error(`${id}: invalid 4x4 sheet geometry`);
    const [source, normalized] = await Promise.all([
      sharp(src).ensureAlpha().raw().toBuffer(), sharp(frames).ensureAlpha().raw().toBuffer()
    ]);
    for (let i = 0; i < 16; i++) {
      const sx = Math.round(i % 4 * sm.width / 4), sy = Math.round(Math.floor(i / 4) * sm.height / 4);
      const sw = Math.round((i % 4 + 1) * sm.width / 4) - sx;
      const sh = Math.round((Math.floor(i / 4) + 1) * sm.height / 4) - sy;
      const fx = i % 4 * frameW, fy = Math.floor(i / 4) * frameH;
      const sourceCount = countOpaque(source, sm.width, sx, sy, sw, sh);
      const frameCount = countOpaque(normalized, fm.width, fx, fy, frameW, frameH);
      if ((i < 15 && (!sourceCount || !frameCount)) || (i === 15 && (sourceCount || frameCount))) throw Error(`${id}: invalid pose cell ${i + 1}`);
    }
    sheets[id] = `assets/characters/2026-11-15_${id}-motion-v2-frames.png`;
  }
  const manifest = { version: 'haunted-motion-v2-2026-11-15', w: 54, h: 48, ax: 32, density: 2, poses, sheets };
  const output = '/* Generated by tools/2026-10-22_build-motion-v2-art.cjs. */\n(function(root){(root.CQ=root.CQ||{}).CharacterArtV2=' + JSON.stringify(manifest) + ';})(typeof window!=="undefined"?window:globalThis);\n';
  fs.writeFileSync(path.join(root, 'js/2026-10-22_character-art-v2.js'), output);
  console.log('PASS 45 motion poses, 3 empty final cells, 54x48 logical frames');
})().catch(e => { console.error(e); process.exitCode = 1; });

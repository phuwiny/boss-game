  /**
   * แปลงข้อมูลส่วนต่าง ๆ เป็นโครงสร้างด่าน
   * @param {string[][]} sections
   * @param {{staticPlatforms?: boolean}} [opts] staticPlatforms = แปลงรางเป็นแผ่นไม้นิ่ง (ใช้ในตัวตรวจด่าน)
   */
  CQ.parseLevel = function (sections, opts) {
    opts = opts || {};
    const TILE = CQ.TILE;
    const T = 32;
    const h = CQ.LEVEL_ROWS;
    const errors = [];
    const rows = [];
    for (let r = 0; r < h; r++) rows.push('');

    sections.forEach(function (sec, si) {
      if (sec.length !== h) errors.push('ส่วนที่ ' + (si + 1) + ' มี ' + sec.length + ' แถว (ต้องมี ' + h + ')');
      const w = sec[0] ? sec[0].length : 0;
      for (let r = 0; r < h; r++) {
        const line = sec[r] || '';
        if (line.length !== w) errors.push('ส่วนที่ ' + (si + 1) + ' แถว ' + r + ' กว้าง ' + line.length + ' (ต้องกว้าง ' + w + ')');
        rows[r] += (line + '.'.repeat(w)).slice(0, w);
      }
    });

    const w = rows[0].length;
    const tiles = new Uint8Array(w * h);
    const lv = {
      w: w, h: h, tiles: tiles,
      coins: [], enemies: [], checkpoints: [], platforms: [], tracks: [],
      start: null, errors: errors
    };

    for (let ty = 0; ty < h; ty++) {
      let trackStart = -1;
      for (let tx = 0; tx <= w; tx++) {
        const ch = tx < w ? rows[ty][tx] : '.';
        if (ch === '~') { if (trackStart < 0) trackStart = tx; }
        else if (trackStart >= 0) {
          lv.tracks.push({ tx0: trackStart, tx1: tx - 1, ty: ty });
          trackStart = -1;
        }
        if (tx === w) break;
        const i = ty * w + tx;
        switch (ch) {
          case '#': tiles[i] = TILE.GROUND; break;
          case 'B': tiles[i] = TILE.BRICK; break;
          case '=': tiles[i] = TILE.ONEWAY; break;
          case '^': tiles[i] = TILE.SPIKE; break;
          case 'S': tiles[i] = TILE.SPRING; break;
          case '~': if (opts.staticPlatforms) tiles[i] = TILE.ONEWAY; break;
          case 'o': lv.coins.push({ tx: tx, ty: ty, x: tx * T + T / 2, y: ty * T + T / 2 }); break;
          case 's': lv.enemies.push({ tx: tx, ty: ty }); break;
          case 'C': lv.checkpoints.push({ tx: tx, ty: ty }); break;
          case 'P':
            if (lv.start) errors.push('พบจุดเริ่มต้น P มากกว่า 1 จุด');
            lv.start = { tx: tx, ty: ty };
            break;
          case '.': break;
          default: errors.push('ไม่รู้จักสัญลักษณ์ "' + ch + '" ที่ (' + tx + ', ' + ty + ')');
        }
      }
    }

    if (!lv.start) { errors.push('ไม่พบจุดเริ่มต้น P'); lv.start = { tx: 1, ty: 0 }; }

    // หนามและสปริงต้องวางบนพื้นทึบ
    for (let ty = 0; ty < h; ty++) {
      for (let tx = 0; tx < w; tx++) {
        const t = tiles[ty * w + tx];
        if (t !== TILE.SPIKE && t !== TILE.SPRING) continue;
        const below = ty + 1 < h ? tiles[(ty + 1) * w + tx] : TILE.EMPTY;
        if (below !== TILE.GROUND && below !== TILE.BRICK) errors.push('หนาม/สปริงที่ (' + tx + ', ' + ty + ') ไม่ได้วางบนพื้นทึบ');
      }
    }

    if (!opts.staticPlatforms) {
      const PW = 96;
      lv.tracks.forEach(function (tr) {
        const minX = tr.tx0 * T;
        const maxX = Math.max(minX, (tr.tx1 + 1) * T - PW);
        lv.platforms.push({ x: minX, y: tr.ty * T, w: PW, h: 14, minX: minX, maxX: maxX, dir: 1, speed: 70, wait: 0.5, waitT: 0, dx: 0, vx: 0 });
      });
    }

    return lv;
  };
